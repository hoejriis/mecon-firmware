"""Public test vectors for signed updates (docs/contract/UPDATES.md): release manifests signed with the release test key.

Every key is derived from a public label, so these are test keys, valid nowhere. Deterministic (Ed25519 signing is
deterministic): running it twice gives the same bytes.

    python3 tools/mecon_update_vectors.py            # rewrite the fixture and the C header
    python3 tools/mecon_update_vectors.py --check    # exit 1 if either file differs from what this would write
"""
import base64
import hashlib
import json
import os
import sys

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIXTURE = os.path.join(ROOT, "test", "fixtures", "updates_public_v1.json")
HEADER = os.path.join(ROOT, "test", "test_updates", "vectors.h")
DOMAIN = b"MECON-RELEASE-v1"
MANIFEST_MAX = 640


class Key:
    def __init__(self, label):
        self.label = "mecon-firmware public test key: " + label
        self.seed = hashlib.sha256(self.label.encode()).digest()
        self._sk = Ed25519PrivateKey.from_private_bytes(self.seed)
        self.public = self._sk.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)
        self.key_id = hashlib.sha256(self.public).digest()[:8].hex()

    def sign(self, text):
        return base64.b64encode(self._sk.sign(DOMAIN + b"\x00" + text.encode())).decode()


RELEASE = Key("release test")       # the one in docs/contract/release-keys.json
STRANGER = Key("release stranger")  # a valid key that is no anchor


def manifest(**over):
    m = {"v": 1, "key_id": RELEASE.key_id, "line": "public", "version": "v1.18.0-mecon.0.3.0",
         "build": hashlib.sha1(b"mecon-firmware test build").hexdigest(), "upstream": "v1.18.0", "interface": "1.0",
         "hardware": "Test Board", "hardware_rev": ["1"], "role": "companion", "variant": "test_variant",
         "layout": 1, "bootloader_min": None, "data_format": 1, "security_version": 1,
         "image": {"size": 1234, "sha256": hashlib.sha256(b"a test image").hexdigest()},
         "kind": "app", "min_from": "v1.18.0-mecon.0.1.0", "downgrade": False, "issued_at": 1790000000}
    m.update(over)
    return json.dumps(m, separators=(",", ":"))


def entry(text, key=RELEASE, sig_over=None):
    return {"manifest": text, "manifest_sig": key.sign(sig_over if sig_over is not None else text)}


def longest():
    """Every field filled in, at the longest this firmware accepts (UpdManifest.h)."""
    return manifest(version="v1.18.0-mecon.999.999.99", min_from="v1.18.0-mecon.999.999.99",
                    build="f" * 40, upstream="v1.18.0-" + "u" * 7, interface="1.0",
                    hardware="H" * 24, hardware_rev=["r" * 8] * 2, role="r" * 12, variant="v" * 48,
                    layout=65535, bootloader_min=16777215, data_format=65535, security_version=65535,
                    image={"size": 16777216, "sha256": "f" * 64}, kind="bootloader-dfu",
                    downgrade=False, issued_at=4294967295)


def build():
    valid = manifest()
    dup = valid[:-1] + ',"v":1}'
    longest_text = longest()
    assert len(longest_text) <= MANIFEST_MAX, len(longest_text)
    stage_max = {"v": 1, "id": "u-1", "op": "update.manifest",
                 "args": entry(longest_text.ljust(MANIFEST_MAX))}
    return {
        "about": "Public update vectors (docs/contract/UPDATES.md). Every key is derived from a public label and is "
                 "valid nowhere. Generated by tools/mecon_update_vectors.py.",
        "release_key": {"label": RELEASE.label, "seed_hex": RELEASE.seed.hex(), "public_key": RELEASE.public.hex(),
                        "key_id": RELEASE.key_id},
        "valid": entry(valid),
        "longest": dict(entry(longest_text), bytes=len(longest_text)),
        "stage_request_max_bytes": len(json.dumps(stage_max, separators=(",", ":"))),
        "refused": {
            "bad_signature": dict(entry(valid, sig_over=valid.replace("0.3.0", "0.3.1")), error="bad-release-signature"),
            "unknown_key": dict(entry(manifest(key_id=STRANGER.key_id), key=STRANGER), error="untrusted-release-key"),
            "duplicate_key": dict(entry(dup), error="bad-manifest"),
            "unknown_field": dict(entry(valid[:-1] + ',"extra":1}'), error="bad-manifest"),
            "wrong_target": dict(entry(manifest(hardware="Another Board")), error="wrong-target"),
        },
    }


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def header(v):
    lines = ["#pragma once", "// Generated by tools/mecon_update_vectors.py from test/fixtures/updates_public_v1.json. Do not edit.",
             "struct UpdVector { const char* name; const char* manifest; const char* sig; const char* error; };",
             "static const UpdVector UPD_VALID = {\"valid\", %s, %s, nullptr};" % (c_string(v["valid"]["manifest"]), c_string(v["valid"]["manifest_sig"])),
             "static const UpdVector UPD_LONGEST = {\"longest\", %s, %s, nullptr};" % (c_string(v["longest"]["manifest"]), c_string(v["longest"]["manifest_sig"])),
             "static const UpdVector UPD_REFUSED[] = {"]
    for name, r in v["refused"].items():
        lines.append("  {\"%s\", %s, %s, \"%s\"}," % (name, c_string(r["manifest"]), c_string(r["manifest_sig"]), r["error"]))
    lines.append("};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    v = build()
    fixture = json.dumps(v, indent=2) + "\n"
    head = header(v)
    if "--check" in sys.argv:
        bad = [p for p, t in ((FIXTURE, fixture), (HEADER, head)) if not os.path.exists(p) or open(p).read() != t]
        if bad:
            sys.exit("out of date: %s; run tools/mecon_update_vectors.py" % ", ".join(os.path.relpath(p, ROOT) for p in bad))
        print("update vectors up to date")
    else:
        os.makedirs(os.path.dirname(HEADER), exist_ok=True)
        open(FIXTURE, "w").write(fixture)
        open(HEADER, "w").write(head)
        print("longest manifest %d bytes, stage request with a %d-byte manifest %d bytes" % (
            v["longest"]["bytes"], MANIFEST_MAX, v["stage_request_max_bytes"]))
