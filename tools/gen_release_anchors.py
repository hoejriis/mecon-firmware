#!/usr/bin/env python3
"""Generate the release anchors (docs/contract/UPDATES.md section 3) from docs/contract/release-keys.json.

    python3 tools/gen_release_anchors.py            # rewrite src/helpers/updates/ReleaseAnchors.h
    python3 tools/gen_release_anchors.py --check    # exit 1 if the header differs from what this would write

Production keys go into every build. Test keys go only into builds that define MECON_RELEASE_TEST_ANCHORS (the
simulated boards and the native tests), and the header refuses to compile them into a firmware build.
"""
import hashlib
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KEYS = os.path.join(ROOT, "docs", "contract", "release-keys.json")
HEADER = os.path.join(ROOT, "src", "helpers", "updates", "ReleaseAnchors.h")


def c_bytes(b):
    return "{" + ", ".join("0x%02x" % x for x in b) + "}"


def entries(keys):
    out = []
    for k in keys:
        pub = bytes.fromhex(k["public_key"])
        kid = hashlib.sha256(pub).digest()[:8]
        if len(pub) != 32 or kid.hex() != k["key_id"]:
            sys.exit("release-keys.json: key_id %s does not match its public key" % k["key_id"])
        if k["use"] not in ("production", "test") or not k["line"]:
            sys.exit("release-keys.json: bad entry %s" % k["key_id"])
        out.append('  {"%s", %s,\n   %s},   // %s' % (k["line"], c_bytes(kid), c_bytes(pub), k["key_id"]))
    return out


def array(name, keys):
    if not keys:
        return "static const Anchor* const %s = nullptr;\nstatic const size_t %s_COUNT = 0;\n" % (name, name)
    return "static const Anchor %s[] = {\n%s\n};\nstatic const size_t %s_COUNT = %d;\n" % (
        name, "\n".join(entries(keys)), name, len(keys))


def render():
    keys = json.load(open(KEYS))["keys"]
    prod = [k for k in keys if k["use"] == "production"]
    test = [k for k in keys if k["use"] == "test"]
    return """#pragma once
// Generated by tools/gen_release_anchors.py from docs/contract/release-keys.json. Do not edit: change the JSON and run
// the tool (CI runs it with --check). docs/contract/UPDATES.md section 3.
#include <stddef.h>
#include <stdint.h>

namespace Upd {

struct Anchor {
  const char* line;
  uint8_t key_id[8];   // the first 8 bytes of SHA-256 over the public key
  uint8_t key[32];
};

// Production keys: in every build.
%s
// Test keys: only in the simulated boards and the native tests, never in a firmware build.
#if defined(MECON_RELEASE_TEST_ANCHORS)
#if !defined(SIM_FREE_HEAP) && (defined(ESP_PLATFORM) || defined(NRF52_PLATFORM) || defined(ARDUINO))
#error "a test release key may not reach a firmware build (MECON_RELEASE_TEST_ANCHORS)"
#endif
%s#else
static const Anchor* const TEST_ANCHORS = nullptr;
static const size_t TEST_ANCHORS_COUNT = 0;
#endif

}  // namespace Upd
""" % (array("PRODUCTION_ANCHORS", prod), array("TEST_ANCHORS", test))


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        cur = open(HEADER).read() if os.path.exists(HEADER) else ""
        if cur != text:
            sys.exit("src/helpers/updates/ReleaseAnchors.h is out of date: run tools/gen_release_anchors.py")
        print("release anchors up to date")
    else:
        open(HEADER, "w").write(text)
        print("wrote", os.path.relpath(HEADER, ROOT))
