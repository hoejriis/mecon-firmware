#!/usr/bin/env python3
"""Writes test/fixtures/key_export_v1.json: a public mecon-kx-v1 vector for a Backend's unwrap (identity.key.export).
Every key in it is a test key derived from a public label, valid nowhere. The wrap is made by tools/mecon_kx.py, which the
simulator tests show equal, byte for byte, to the firmware's (sim/tests/test_key_export.py)."""
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, ".."))
import mecon_kx  # noqa: E402
from sim import ed25519_ref  # noqa: E402

ROOT = os.path.join(HERE, "..")
V = json.load(open(os.path.join(ROOT, "test", "fixtures", "deployment_authority_public_v1.json")))
member = V["keys"]["instance a"]
node_seed = hashlib.sha256(b"mecon-kx-v1 test node").digest()
node_pub = ed25519_ref.public_key(node_seed)
h = bytearray(hashlib.sha512(node_seed).digest())   # MeshCore's 64-byte private key: the expanded, clamped seed
h[0] &= 248; h[31] &= 63; h[31] |= 64
job = 1234
shared = mecon_kx.shared_secret(bytes.fromhex(member["seed_hex"]), node_pub)
wrapped = mecon_kx.wrap(shared, job, bytes(h))
assert mecon_kx.unwrap(bytes.fromhex(member["seed_hex"]), node_pub, job, wrapped) == bytes(h)
out = {
    "about": "Public test vector for mecon-kx-v1 (src/helpers/iface/KeyWrap.h). Test keys from public labels; never valid "
             "anywhere. Generated by tools/mecon_kx_vectors.py.",
    "member": {"instance_id": V["instance_ids"]["a"],
               "seed_hex": member["seed_hex"], "public_key": member["public_key"]},
    "node": {"label": "mecon-kx-v1 test node", "public_key": node_pub.hex(), "private_key_hex": bytes(h).hex()},
    "job_id": job,
    "shared_secret_hex": shared.hex(),
    "wrapped_b64": __import__("base64").b64encode(wrapped).decode(),
}
path = os.path.join(ROOT, "test", "fixtures", "key_export_v1.json")
json.dump(out, open(path, "w"), indent=2)
open(path, "a").write("\n")
print("wrote", path)
