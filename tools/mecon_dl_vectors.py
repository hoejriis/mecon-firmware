#!/usr/bin/env python3
"""Writes test/fixtures/delegate_seal_v1.json: a public mecon-dl-v1 vector for a Backend's sealing (identity.delegate.put).
Every key in it is a test key derived from a public label, valid nowhere. The seal is made by tools/mecon_dl.py, which the
simulator tests show opens on the firmware (sim/tests/test_delegates.py), and whose KDF and tag the native tests check
(test/test_delegate_seal)."""
import base64
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, ".."))
import mecon_dl  # noqa: E402
import mecon_kx  # noqa: E402
from sim import ed25519_ref  # noqa: E402

ROOT = os.path.join(HERE, "..")
V = json.load(open(os.path.join(ROOT, "test", "fixtures", "deployment_authority_public_v1.json")))
member = V["keys"]["instance a"]
node_seed = hashlib.sha256(b"mecon-kx-v1 test node").digest()   # the node key of the mecon-kx-v1 vector
node_pub = ed25519_ref.public_key(node_seed)
node_prv = mecon_dl.private_key(node_seed)
d_seed = hashlib.sha256(b"mecon-dl-v1 test delegated identity").digest()
d_pub = ed25519_ref.public_key(d_seed)
d_prv = mecon_dl.private_key(d_seed)
assert d_pub[0] not in (0x00, 0xFF)
eph_seed = hashlib.sha256(b"mecon-dl-v1 test ephemeral").digest()
job, slot = 2345, 1
sealed = mecon_dl.seal(eph_seed, node_pub, job, slot, d_pub, d_prv)
assert mecon_dl.unseal(node_prv, job, slot, d_pub, sealed) == d_prv
shared = mecon_kx.shared_secret(eph_seed, node_pub)
k = mecon_dl.kdf(shared, job, slot, ed25519_ref.public_key(eph_seed), d_pub)
out = {
    "about": "Public test vector for mecon-dl-v1 (src/helpers/iface/DelegateSeal.h, docs/contract/AUTHORITY.md section 10b). Test "
             "keys from public labels; never valid anywhere. Generated by tools/mecon_dl_vectors.py.",
    "node": {"label": "mecon-kx-v1 test node", "public_key": node_pub.hex(), "private_key_hex": node_prv.hex()},
    "delegated": {"label": "mecon-dl-v1 test delegated identity", "public_key": d_pub.hex(), "private_key_hex": d_prv.hex()},
    "ephemeral": {"label": "mecon-dl-v1 test ephemeral", "seed_hex": eph_seed.hex(), "public_key": ed25519_ref.public_key(eph_seed).hex()},
    "job_id": job,
    "slot": slot,
    "shared_secret_hex": shared.hex(),
    "k_hex": k.hex(),
    "sealed_b64": base64.b64encode(sealed).decode(),
    "request_args": {"slot": slot, "pub": d_pub.hex(), "sealed": base64.b64encode(sealed).decode()},
    "member": {"instance_id": V["instance_ids"]["a"], "public_key": member["public_key"]},
}
path = os.path.join(ROOT, "test", "fixtures", "delegate_seal_v1.json")
json.dump(out, open(path, "w"), indent=2)
open(path, "a").write("\n")
print("wrote", path)
